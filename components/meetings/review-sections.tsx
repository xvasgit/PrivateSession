import { MeetingActionForm } from "./meeting-form";
import type { MeetingReview } from "@/lib/meetings/review";

export function ReviewSections({
  meetingId,
  review,
}: {
  meetingId: number;
  review: MeetingReview | null;
}) {
  const sections = [
    { name: "summary", label: "Summary", id: "summary" },
    { name: "insights", label: "Insights", id: "insights" },
    { name: "followUps", label: "Follow-ups", id: "follow-ups" },
  ] as const;
  return (
    <div className="mt-10 space-y-5">
      <p className="text-sm text-slate-600">
        Manual review notes — written by you, not generated by AI.
      </p>
      {sections.map(({ name, label, id }) => (
        <section
          key={id}
          id={id}
          className="scroll-mt-6 rounded-xl border border-slate-200 bg-white p-5"
        >
          <h2 className="text-xl font-bold">{label}</h2>
          {review ? (
            <p className="mt-3 whitespace-pre-wrap break-words text-slate-700">
              {review[name] || `No ${label.toLowerCase()} added yet.`}
            </p>
          ) : (
            <p className="mt-3 text-red-800">Review unavailable.</p>
          )}
        </section>
      ))}
      {review === null ? (
        <p role="alert" className="text-red-800">
          The saved review could not be authenticated and decrypted. Editing is
          blocked to protect the existing notes. Check the original encryption
          key and stored data.
        </p>
      ) : (
        <details className="rounded-xl border border-slate-200 bg-white p-5">
          <summary className="cursor-pointer font-semibold text-teal-800">
            Edit review
          </summary>
          <p className="mt-3 text-sm text-slate-600">
            All fields are optional, up to 10,000 characters each. Save all
            three empty to clear the review. Follow-ups are notes, not scheduled
            tasks.
          </p>
          <MeetingActionForm
            operation="saveReview"
            hidden={{ id: meetingId }}
            submit="Save review"
            fields={sections.map(({ name, label }) => ({
              name,
              label,
              type: "textarea",
              optional: true,
              max: 10000,
              value: review[name],
            }))}
          />
        </details>
      )}
    </div>
  );
}
